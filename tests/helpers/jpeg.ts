/**
 * A real, decodable baseline JPEG of a chosen size — uniform mid-grey.
 *
 * WHY: tests and the admin fixture used to borrow a doctor's-work photograph
 * (a patient image) as their "sample JPEG". Since ADR 0010 the doctor can
 * delete those through the CMS, and doing so must never break CI and block
 * the public deploy. So the sample is generated here: no image is committed,
 * nothing depends on site content, and no patient material is copied.
 *
 * Grayscale, one component, the standard luminance Huffman tables (JPEG spec
 * Annex K). Every 8×8 block is DC difference 0 (code "00") then end-of-block
 * (code "1010") — a flat image, but structurally a complete JPEG that browsers
 * decode and the Worker's inspector accepts.
 */


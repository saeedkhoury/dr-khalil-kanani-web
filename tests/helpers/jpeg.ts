function segment(marker: number, body: number[]): number[] {
  const length = body.length + 2;
  return [0xff, marker, length >> 8, length & 0xff, ...body];
}

export function solidJpeg(width: number, height: number): Buffer {
  const blocks = Math.ceil(width / 8) * Math.ceil(height / 8);
  // "00" + "1010" per block = 6 bits; pad the last byte with 1s.
  const bits = '001010'.repeat(blocks);
  const padded = bits + '1'.repeat((8 - (bits.length % 8)) % 8);
  const scan: number[] = [];
  for (let i = 0; i < padded.length; i += 8) {
    const byte = Number.parseInt(padded.slice(i, i + 8), 2);
    scan.push(byte);
    if (byte === 0xff) scan.push(0x00); // byte stuffing
  }
  return Buffer.from([
    0xff, 0xd8,
    ...segment(0xdb, [0x00, ...new Array(64).fill(1)]),
    ...segment(0xc0, [8, height >> 8, height & 0xff, width >> 8, width & 0xff, 1, 1, 0x11, 0]),
    ...segment(0xc4, [0x00, ...DC_COUNTS, ...DC_VALUES]),
    ...segment(0xc4, [0x10, ...AC_COUNTS, ...AC_VALUES]),
    ...segment(0xda, [1, 1, 0x00, 0, 63, 0]),
    ...scan,
    0xff, 0xd9,
  ]);
}
